"""> ### csv 파일 전처리"""

# 특정 column만 가져오기
df = df.loc[:, ['Hits', 'HmRun', 'Salary']]
df.head()

# Missing 데이터 제거
df = df.dropna()
df.head()

# Salary를 상(2), 중(1), 하(0)으로 구분
df.loc[df['Salary'] >= 600, 'Salary2'] = 2
df.loc[(df['Salary'] >= 250) & (df['Salary'] < 600), 'Salary2'] = 1
df.loc[df['Salary'] < 250, 'Salary2'] = 0
df.head()

# Salary2가 0인 데이터 개수, 1인 데이터 개수, 2인 데이터 개수를 출력
salary2 = df['Salary2']
print(salary2.value_counts())

input = np.array(df[['Hits', 'HmRun']], dtype= np.float32)
target = np.array(df['Salary2'], dtype= np.float32).reshape((-1,1))

print(input.shape)
print(input[:10])
print(target.shape)
print(target[:10])

target_onehot = tf.one_hot(target.reshape((-1,)), 3)

x_input = tf.constant(input, dtype=tf.float32)
labels = tf.constant(target_onehot, dtype=tf.float32)

print(x_input.shape)
print(x_input[:10])
print(labels.shape)
print(labels[:10])

from sklearn.preprocessing import MinMaxScaler

scaler = MinMaxScaler()
x_input_scaled = scaler.fit_transform(x_input)
x_input_scaled = tf.constant(x_input_scaled, dtype=tf.float32)

print(x_input_scaled.shape)
print(x_input_scaled[:5])

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense

# 2. Keras Model 정의
model = Sequential([
    Dense(32, activation='relu', input_shape=(2,)), # Input layer with 2 features
    Dense(16, activation='relu'),
    Dense(3, activation='softmax') # Output layer for 3 classes (0, 1, 2)
])

# Model compile
model.compile(optimizer='Adam', loss='categorical_crossentropy', metrics=['accuracy'])

# Model summary
model.summary()

