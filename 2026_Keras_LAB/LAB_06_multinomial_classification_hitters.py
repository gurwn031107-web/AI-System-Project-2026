# 7. (Hits가 171, HmRun이 10일 때 Salary를 0, 1, 2로 예측)
new_data = np.array([[171.0, 10.0]], dtype=np.float32)

# Scale the new data using the fitted scaler
new_data_scaled = scaler.transform(new_data)
new_data_scaled = tf.constant(new_data_scaled, dtype=tf.float32)

# Predict
new_prediction = model.predict(new_data_scaled)
new_predicted_class = np.argmax(new_prediction, axis=1)[0]

print(f"Predicted probabilities for (Hits=171, HmRun=10): {new_prediction[0]}")
print(f"Predicted Salary category (0: Low, 1: Mid, 2: High) for (Hits=171, HmRun=10): {new_predicted_class}")

# 8. x_input을 시각화 -> Hits를 x축, HmRun을 y축으로 -> labels에 따라 색깔을 R(0), G(1), B(2) dot로 표시하는 그래프 출력
