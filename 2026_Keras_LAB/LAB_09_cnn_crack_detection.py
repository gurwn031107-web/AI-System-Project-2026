def Make_Result_Plot(model, X_data, y_true_labels, title='Predictions', num_samples=10):
    predictions = model.predict(X_data)
    predicted_labels = np.argmax(predictions, axis=1)
    true_labels_decoded = np.argmax(y_true_labels, axis=1)

    plt.figure(figsize=(15, 10))
    for i in range(num_samples):
        idx = np.random.randint(0, len(X_data))
        plt.subplot(2, 5, i + 1)
        plt.imshow(X_data[idx])
        plt.title(f"True: {true_labels_decoded[idx]} | Pred: {predicted_labels[idx]} ({'O' if true_labels_decoded[idx] == predicted_labels[idx] else 'X'})")
        plt.axis('off')
    plt.suptitle(title)
    plt.tight_layout()
    plt.show()

